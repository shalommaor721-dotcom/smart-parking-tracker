#!/usr/bin/env bash
# הסקריפט הזה מדמה את המצלמה של החניון.
# מצלמה אמיתית מזהה לוחית ושולחת אותה לשרת. הסקריפט עושה בדיוק את זה.
#
# איך מפעילים:
#   ./simulate.sh                  שולח לוחית אקראית
#   ./simulate.sh 123-45-678       שולח לוחית מסוימת

# קובעים את הלוחית: אם כתבנו אחת אחרי שם הסקריפט משתמשים בה.
# אם לא, יוצרים לוחית אקראית בפורמט 123-45-678 (המספר %03d אומר שתמיד יהיו 3 ספרות, עם אפסים בהתחלה אם צריך)
PLATE="${1:-$(printf '%03d-%02d-%03d' $((RANDOM%1000)) $((RANDOM%100)) $((RANDOM%1000)))}"
# קובעים את כתובת השרת: אם כתבנו אחת כמילה שנייה משתמשים בה, ואחרת הכתובת הרגילה במחשב שלנו
API="${2:-http://localhost:3000}"

# מדפיסים איזו לוחית נשלחת
echo "Camera detected plate: $PLATE"
# שולחים את הלוחית לשרת. בשורה הראשונה: -s = בלי הצגת התקדמות, -X POST = שליחת מידע חדש
# בשורה השנייה: אומרים לשרת שהמידע בפורמט JSON
# בשורה השלישית: המידע עצמו, הלוחית
curl -s -X POST "$API/api/plates" \
  -H "Content-Type: application/json" \
  -d "{\"plate\":\"$PLATE\"}"
# שורה ריקה בסוף, כדי שהתשובה לא תידבק לשורת הפקודה הבאה
echo
